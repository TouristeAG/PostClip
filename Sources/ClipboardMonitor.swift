import AppKit

/// Surveille NSPasteboard.general via son changeCount (aucune API de notification n'existe sur macOS).
/// Une simple comparaison d'entier toutes les 0,5 s : coût CPU négligeable.
final class ClipboardMonitor {
    private let store: ClipboardStore
    private var timer: Timer?
    private var lastChange: Int
    private(set) var lastSignature: String?
    /// true si le contenu actuel n'a pas été enregistré (mot de passe, type non géré…).
    private(set) var currentIsUncaptured = false

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    init(store: ClipboardStore) {
        self.store = store
        lastChange = NSPasteboard.general.changeCount
    }

    func start() {
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        t.tolerance = 0.25
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    /// Le presse-papiers contient-il encore exactement ce qu'on a capturé en dernier ?
    func isUnchanged(signature: String) -> Bool {
        NSPasteboard.general.changeCount == lastChange && lastSignature == signature
    }

    /// À appeler après avoir écrit nous-mêmes dans le presse-papiers.
    func adoptCurrentChange(signature: String?) {
        lastChange = NSPasteboard.general.changeCount
        lastSignature = signature
        currentIsUncaptured = false
    }

    func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        capture(pb)
    }

    private func capture(_ pb: NSPasteboard) {
        let types = pb.types ?? []
        let ids = Set(types.map(\.rawValue))
        currentIsUncaptured = true
        lastSignature = nil
        guard ids.isDisjoint(with: Self.ignoredTypes) else { return }

        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier

        // 1. Fichiers (Finder)
        if types.contains(.fileURL),
           let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path)
            let sig = "f:" + paths.joined(separator: "\n")
            finish(sig)
            if store.bump(signature: sig, source: source) { return }
            store.insert(ClipItem(kind: .files, filePaths: paths, signature: sig, date: Date(), sourceBundleID: source))
            return
        }

        // 2. Texte
        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let sig = ClipItem.signature(prefix: "t:", data: Data(s.utf8))
            finish(sig)
            if store.bump(signature: sig, source: source) { return }
            store.insert(ClipItem(kind: .text, text: s, signature: sig, date: Date(), sourceBundleID: source))
            return
        }

        // 3. Image
        if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff) {
            let sig = ClipItem.signature(prefix: "i:", data: data)
            finish(sig)
            if store.bump(signature: sig, source: source) { return }
            let id = UUID()
            let store = self.store
            store.ioQueue.async {
                guard let size = store.writeImage(data: data, id: id) else { return }
                DispatchQueue.main.async {
                    store.insert(ClipItem(id: id, kind: .image, imageWidth: size.width, imageHeight: size.height,
                                          signature: sig, date: Date(), sourceBundleID: source))
                }
            }
        }
    }

    private func finish(_ sig: String) {
        lastSignature = sig
        currentIsUncaptured = false
    }
}
